-- Run this in Supabase SQL Editor.
-- Create an admin user in Supabase Authentication separately.
create table if not exists public.page_views (
  id bigint generated by default as identity primary key,
  path text not null,
  country text default 'Unknown',
  referrer text,
  created_at timestamptz not null default now()
);

create table if not exists public.site_content (
  key text primary key,
  value jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

alter table public.page_views enable row level security;
alter table public.site_content enable row level security;

-- Anyone can add a page-view event; only authenticated admins can read analytics.
create policy "allow anonymous page view inserts"
on public.page_views for insert to anon, authenticated
with check (true);

create policy "admins can read page views"
on public.page_views for select to authenticated
using (true);

create policy "public can read site content"
on public.site_content for select to anon, authenticated
using (true);

create policy "authenticated admins can edit site content"
on public.site_content for all to authenticated
using (true) with check (true);

-- For a production deployment, replace broad authenticated policies with an
